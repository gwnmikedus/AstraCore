"""Bundle the trailer's scenes (docs/demo/trailer/film) for the live home hero.

Writes src/astracore/static/js/hero-film-scenes.js, js/hero-film-score.js (the soundtrack, loaded only when a pilot
turns sound on) and src/astracore/static/css/hero-film.css. The film was written for the Motion player;
js/hero-film.js is the small player the hero uses instead (js/hero-film-audio.js plays the score). Two changes make
it fit the site:

* The scenes' inline `style="..."` attributes become `data-css="..."`: the site's content security policy forbids
  style attributes, and the player applies these declarations through CSSOM instead.
* base.css is scoped to the hero's stage, so its short class names (.line, .muted, .panel) can't touch the page.

Run it after replacing the files in docs/demo/trailer/film; tests/test_hero_film.py fails while the output is stale.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FILM = ROOT / "docs" / "demo" / "trailer" / "film"
JS_OUT = ROOT / "src" / "astracore" / "static" / "js" / "hero-film-scenes.js"
SCORE_OUT = ROOT / "src" / "astracore" / "static" / "js" / "hero-film-score.js"
CSS_OUT = ROOT / "src" / "astracore" / "static" / "css" / "hero-film.css"
STAGE = ".hero-film-stage"
HEADER = "Generated by scripts/trailer/build_hero_film.py from docs/demo/trailer/film. Do not edit."

STYLE_ATTR = re.compile(r'\bstyle=(\\?["\'])')


def scenes_js() -> str:
    meta = json.loads((FILM / "scenes.json").read_text())
    order = [{"id": s["id"], "dur": s["dur"]} for s in meta["scenes"]]
    parts = [f"// {HEADER}", "(function () {"]
    for name in ["shared.js"] + [f"scene-{s['id']}.js" for s in order]:
        src = STYLE_ATTR.sub(r"data-css=\1", (FILM / name).read_text())
        parts.append(f"// ---- {name}\n{{\n{src.rstrip()}\n}}")   # a block each: every file declares its own helpers
    parts.append(f"kit.boot({json.dumps(order)});")
    parts.append("})();")
    return "\n".join(parts) + "\n"


def score_js() -> str:
    return f"// {HEADER}\n{{\n{(FILM / 'score.js').read_text().rstrip()}\n}}\n"


def _scope(selectors: str) -> str:
    out = []
    for sel in selectors.split(","):
        sel = sel.strip()
        out.append(STAGE if sel == "#stage" else f"{STAGE} {sel}")
    return ", ".join(out)


def stage_css() -> str:
    css = (FILM / "base.css").read_text()
    rules = re.findall(r"([^{}]+)\{([^{}]*)\}", css)
    lines = [f"/* {HEADER} */"]
    for selectors, body in rules:
        lines.append(f"{_scope(selectors)} {{{body.strip()}}}")
    return "\n".join(lines) + "\n"


def main(check: bool = False) -> int:
    stale = []
    for path, text in ((JS_OUT, scenes_js()), (SCORE_OUT, score_js()), (CSS_OUT, stage_css())):
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
    if stale:
        print("Out of date; run python scripts/trailer/build_hero_film.py:", *stale)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
