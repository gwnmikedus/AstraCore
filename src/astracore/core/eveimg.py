"""EVE images bundled in static/img/eve (from the official EVE Image Server, see manifest.json).

Lookups by type id, item name (PI commodities) and planet type, for Jinja ({{ eve_img('Silicon') }},
{{ planet_img('Lava') }}) and the browser (static/js/eve-images.js: AC.eveImg(name), AC.planetImg(type)).
Anything not bundled (other corporations, alliances, characters) loads live from images.evetech.net.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Dict, Optional

from markupsafe import Markup, escape

EVE_DIR = Path(__file__).resolve().parent.parent / "static" / "img" / "eve"
URL = "/static/img/eve/"
LIVE = "https://images.evetech.net"

# Which bundled structure stands for what in the planner.
STRUCTURES = {"miner": 2848, "factory": 2474, "factory_p4": 2475, "basic": 2473, "launchpad": 2544,
              "storage": 2541, "command_center": 2524}


@lru_cache(maxsize=1)
def _index() -> dict:
    try:
        m = json.loads((EVE_DIR / "manifest.json").read_text())
    except (OSError, ValueError):
        return {"type": {}, "name": {}, "planet": {}, "logo": {}}
    by_type: Dict[int, str] = {}
    by_name: Dict[str, str] = {}
    planets: Dict[str, str] = {}
    logos: Dict[str, str] = {}
    for f in m.get("files", []):
        url = URL + f["path"]
        if f["path"].startswith("logos/"):
            ent = "alliance" if "alliance" in f["path"] else "corporation"
            eid = m["entities"][ent]["id"]
            size = f["path"].rsplit("-", 1)[1].split(".")[0]
            logos[f"{ent}:{eid}:{size}"] = url
            continue
        if f.get("type_id"):
            by_type[int(f["type_id"])] = url
        name = (f.get("name") or "").strip()
        if f["path"].startswith("pi/planets/") and "(" in name:
            planets[name.split("(", 1)[1].rstrip(")").lower()] = url
        elif name:
            by_name[name.lower()] = url
    return {"type": by_type, "name": by_name, "planet": planets, "logo": logos, "entities": m.get("entities", {})}


def url_for(name_or_id) -> Optional[str]:
    idx = _index()
    if isinstance(name_or_id, int) or (isinstance(name_or_id, str) and name_or_id.isdigit()):
        return idx["type"].get(int(name_or_id))
    return idx["name"].get(str(name_or_id or "").strip().lower())


def planet_url(planet_type: str) -> Optional[str]:
    return _index()["planet"].get(str(planet_type or "").strip().lower())


def logo_url(kind: str, entity_id: int, size: int = 64) -> str:
    """Bundled for Dutch Legions / Insidious., live from the image server for everyone else."""
    hit = _index()["logo"].get(f"{kind}:{entity_id}:{size}")
    if hit:
        return hit
    if kind == "character":
        return f"{LIVE}/characters/{entity_id}/portrait?size={size}"
    return f"{LIVE}/{kind}s/{entity_id}/logo?size={size}"


def _img(url: Optional[str], alt: str, size: int, cls: str) -> Markup:
    if not url:
        return Markup("")
    return Markup(f'<img class="eve {cls}" src="{escape(url)}" alt="{escape(alt)}" width="{size}" height="{size}" loading="lazy">')


def eve_img(name_or_id, size: int = 20, cls: str = "") -> Markup:
    return _img(url_for(name_or_id), "", size, cls)


def planet_img(planet_type: str, size: int = 20, cls: str = "") -> Markup:
    return _img(planet_url(planet_type), "", size, cls)


def structure_img(kind: str, size: int = 20, cls: str = "") -> Markup:
    return _img(url_for(STRUCTURES.get(kind, 0)), "", size, cls)


def logo_img(kind: str, entity_id: int, size: int = 32, cls: str = "") -> Markup:
    return _img(logo_url(kind, entity_id, 64 if size <= 64 else 128), "", size, "logo " + cls)


def home_groups() -> dict:
    """The corporation and alliance the bundled logos belong to (manifest entities)."""
    return _index().get("entities", {})


JINJA_GLOBALS = {"eve_img": eve_img, "planet_img": planet_img, "structure_img": structure_img,
                 "logo_img": logo_img, "logo_url": logo_url}


def build_js() -> str:
    idx = _index()
    data = {"name": idx["name"], "planet": idx["planet"],
            "structure": {k: idx["type"].get(v) for k, v in STRUCTURES.items()}}
    return ("// Generated by `python -m astracore.core.eveimg` from static/img/eve/manifest.json. Do not edit.\n"
            "(function () {\n  const E = " + json.dumps(data, separators=(",", ":"), sort_keys=True) + ";\n"
            "  const img = (u, s, c) => u ? `<img class=\"eve ${c || ''}\" src=\"${u}\" alt=\"\" width=\"${s}\" height=\"${s}\" loading=\"lazy\">` : '';\n"
            "  window.AC = window.AC || {};\n"
            "  AC.eveImg = (name, s = 20, c = '') => img(E.name[String(name || '').toLowerCase()], s, c);\n"
            "  AC.planetImg = (type, s = 20, c = '') => img(E.planet[String(type || '').toLowerCase()], s, c);\n"
            "  AC.structureImg = (kind, s = 20, c = '') => img(E.structure[kind], s, c);\n"
            "})();\n")


if __name__ == "__main__":
    out = EVE_DIR.parent.parent / "js" / "eve-images.js"
    out.write_text(build_js())
    print(f"wrote {out}")
