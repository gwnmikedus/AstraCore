"""Inline SVG icons (Lucide ISC and GitHub Octicons MIT; see static/icons/)."""
from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

from markupsafe import Markup

ICON_DIR = Path(__file__).resolve().parent.parent / "static" / "icons"


@lru_cache(maxsize=None)
def _inner(name: str) -> str:
    path = ICON_DIR / f"{name}.svg"
    if not path.exists():
        return ""
    body = re.sub(r"<!--.*?-->", "", path.read_text(), flags=re.S)
    m = re.search(r"<svg[^>]*>(.*)</svg>", body, re.S)
    return re.sub(r"\s+", " ", m.group(1)).strip() if m else ""


def svg(name: str, cls: str = "", label: str = "") -> str:
    aria = f'role="img" aria-label="{label}"' if label else 'aria-hidden="true"'
    return (f'<svg class="ic {cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
            f'stroke-linecap="round" stroke-linejoin="round" {aria}>{_inner(name)}</svg>')


def icon(name: str, cls: str = "", label: str = "") -> Markup:
    """Jinja global: {{ icon('truck') }}."""
    return Markup(svg(name, cls, label))


def build_js() -> str:
    """static/js/icons.js: the same icons for templates rendered in the browser (AC.icon('truck'))."""
    names = sorted(p.stem for p in ICON_DIR.glob("*.svg"))
    data = {n: _inner(n) for n in names}
    return ("// Generated by `python -m astracore.core.icons` from static/icons (Lucide ISC, Octicons MIT). Do not edit.\n"
            "(function () {\n  const I = " + json.dumps(data, separators=(",", ":")) + ";\n"
            "  window.AC = window.AC || {};\n"
            "  AC.icon = (n, cls = '') => `<svg class=\"ic ${cls}\" viewBox=\"0 0 24 24\" fill=\"none\" "
            "stroke=\"currentColor\" stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\" "
            "aria-hidden=\"true\">${I[n] || ''}</svg>`;\n})();\n")


if __name__ == "__main__":
    out = ICON_DIR.parent / "js" / "icons.js"
    out.write_text(build_js())
    print(f"wrote {out}")
