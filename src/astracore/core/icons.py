"""SVG icons (Lucide ISC and GitHub Octicons MIT; see static/icons/) from one sprite.

Every icon lives once in static/img/icons.svg as a <symbol>; a page refers to it with
<svg class="ic"><use href="/static/img/icons.svg?v=<hash>#truck"></use></svg>, so a page with hundreds of icons
carries a few dozen bytes each instead of the whole drawing. The sprite is a hashed static file: browsers fetch it
once and cache it until an icon changes. Colour, stroke width and size still come from the page (`.ic` in CSS),
because the symbol's shapes inherit them from the <svg> that uses it.

Regenerate static/img/icons.svg and static/js/icons.js with `python -m astracore.core.icons` after adding an icon.
"""
from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

from markupsafe import Markup

from . import assets

ICON_DIR = Path(__file__).resolve().parent.parent / "static" / "icons"
SPRITE = ICON_DIR.parent / "img" / "icons.svg"
SPRITE_REL = "img/icons.svg"
ATTRS = ('viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
         'stroke-linecap="round" stroke-linejoin="round"')


@lru_cache(maxsize=None)
def _inner(name: str) -> str:
    path = ICON_DIR / f"{name}.svg"
    if not path.exists():
        return ""
    body = re.sub(r"<!--.*?-->", "", path.read_text(), flags=re.S)
    m = re.search(r"<svg[^>]*>(.*)</svg>", body, re.S)
    return re.sub(r"\s+", " ", m.group(1)).strip() if m else ""


def names() -> list:
    return sorted(p.stem for p in ICON_DIR.glob("*.svg"))


def build_sprite() -> str:
    """static/img/icons.svg: every icon as a <symbol id="name">."""
    symbols = "".join(f'<symbol id="{n}" viewBox="0 0 24 24">{_inner(n)}</symbol>' for n in names())
    return ("<!-- Generated by `python -m astracore.core.icons` from static/icons (Lucide ISC, Octicons MIT). "
            "Do not edit. -->\n"
            f'<svg xmlns="http://www.w3.org/2000/svg">{symbols}</svg>\n')


def sprite_url() -> str:
    return assets.asset(SPRITE_REL)


def svg(name: str, cls: str = "", label: str = "") -> str:
    aria = f'role="img" aria-label="{label}"' if label else 'aria-hidden="true"'
    use = f'<use href="{sprite_url()}#{name}"></use>' if _inner(name) else ""
    return f'<svg class="ic {cls}" {ATTRS} {aria}>{use}</svg>'


def icon(name: str, cls: str = "", label: str = "") -> Markup:
    """Jinja global: {{ icon('truck') }}."""
    return Markup(svg(name, cls, label))


def build_js() -> str:
    """static/js/icons.js: the same markup for templates rendered in the browser (AC.icon('truck'))."""
    return ("// Generated by `python -m astracore.core.icons` from static/icons (Lucide ISC, Octicons MIT). Do not edit.\n"
            "(function () {\n"
            f"  const S = {json.dumps(sprite_url())};\n"
            f"  const N = new Set({json.dumps(names(), separators=(',', ':'))});\n"
            "  window.AC = window.AC || {};\n"
            f"  AC.icon = (n, cls = '') => `<svg class=\"ic ${{cls}}\" {ATTRS} aria-hidden=\"true\">"
            "${N.has(n) ? `<use href=\"${S}#${n}\"></use>` : ''}</svg>`;\n})();\n")


def write() -> None:
    """Write the sprite first: icons.js carries its hash."""
    SPRITE.write_text(build_sprite())
    (ICON_DIR.parent / "js" / "icons.js").write_text(build_js())


if __name__ == "__main__":
    write()
    print(f"wrote {SPRITE} and static/js/icons.js")
